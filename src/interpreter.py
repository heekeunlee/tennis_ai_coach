# ── 상태별 스타일 ──────────────────────────────────────────────────────────────
STATUS_STYLE: Dict[str, Tuple[str, str, str]] = {
    'good':    ('✅', '#eafbea', '#27ae60'),
    'caution': ('⚠️', '#fff8e1', '#f9a825'),
    'bad':     ('🔴', '#ffebee', '#e53935'),
    'info':    ('ℹ️', '#e3f2fd', '#1976d2'),
}

# 표시할 지표 순서 (9종 전체)
DISPLAY_ORDER = [
    'elbow_angle', 'shoulder_angle', 'knee_angle',
    'trunk_inclination', 'shoulder_rotation', 'hip_rotation',
    'wrist_height', 'wrist_trunk_distance', 'followthrough_direction',
]


def get_interpretation(metric_key: str, value: float, phase: str = 'impact') -> Dict:
    """수치에 맞는 해석 딕셔너리 반환"""
    norms = RANGES.get(metric_key, {})
    ranges = norms.get(phase) or norms.get('default') or []

    matched_status, matched_msg = 'info', '이 값에 대한 해석 정보가 없습니다.'
    for lo, hi, status, msg in ranges:
        if lo <= value < hi:
            matched_status, matched_msg = status, msg
            break
    else:
        if ranges:
            *_, matched_status, matched_msg = ranges[-1]

    icon, bg, border = STATUS_STYLE.get(matched_status, STATUS_STYLE['info'])
    return {
        'status':       matched_status,
        'message':      matched_msg,
        'icon':         icon,
        'bg_color':     bg,
        'border_color': border,
    }


def format_value(metric_key: str, value: float) -> str:
    unit = METRIC_UNIT.get(metric_key, '')
    return f'{value:.2f}{unit}'
