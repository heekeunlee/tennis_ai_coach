const PHASE_KEY = { '레디 포지션':'ready','테이크백':'takeback','임팩트':'impact','팔로스루':'followthrough' };

export function generateCoaching(topDiffs) {
  return topDiffs.flatMap(d => {
    const { metric, uv, pv, phase } = d;
    if (uv == null || pv == null) return [];
    const dir = uv < pv ? 'too_low' : 'too_high';
    const rules = COACHING[metric]?.[dir] ?? {};
    const key = PHASE_KEY[phase] ?? 'default';
    const msg = rules[key] ?? rules.default ?? '';
    return msg ? [msg] : [];
  });
}

export function generateRecs(topDiffs) {
  const seen = new Set(), out = [];
  for (const { metric } of topDiffs) {
    if (seen.has(metric)) continue;
    seen.add(metric);
    (RECS[metric] ?? []).forEach(r => { if (out.length < 5) out.push(r); });
  }
  return out;
}
