export function getInterpretation(metricKey, value, phase) {
  const ranges = R[metricKey]?.[phase] ?? R[metricKey]?.default ?? [];
  for (const [lo, hi, status, msg] of ranges) {
    if (value >= lo && value < hi) return { status, message: msg };
  }
  if (ranges.length) {
    const [,, status, message] = ranges[ranges.length - 1];
    return { status, message };
  }
  return { status: 'info', message: '이 값에 대한 해석 정보가 없습니다.' };
}

